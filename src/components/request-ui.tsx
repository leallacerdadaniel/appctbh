const capitalize = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);

/** What the request is, in one line ("Laverie", "Réparation · Plomberie"). */
export function requestTitle(req: AnyRequest, lang: Lang, t: Strings) {
  const r = t.requests;
  switch (req.kind) {
    case 'service':
      return serviceById(req.serviceId)?.name[lang] ?? r.kinds.service;
    case 'maintenance':
      return `${r.kinds.maintenance} · ${r.maintenanceCategories[req.category]}`;
    default:
      return r.kinds[req.kind];
  }
}

const CATEGORY_ICON: Record<ServiceCategory, IconName> = {
  cleaning: 'sparkles',
  laundry: 'laundry',
  chef: 'restaurant',
  transfer: 'car',
};

export function serviceCategoryIcon(category: ServiceCategory): IconName {
  return CATEGORY_ICON[category];
}

export function requestIcon(req: AnyRequest): IconName {
  switch (req.kind) {
    case 'service': {
      const svc = serviceById(req.serviceId);
      return svc ? CATEGORY_ICON[svc.category] : 'receipt';
    }
    case 'maintenance':
      return 'wrench';
    case 'late_checkout':
      return 'luggage';
    case 'early_checkin':
      return 'key';
    case 'gourmet':
      return 'grill';
  }
}

/** "Jeudi 6 novembre" */
export function longDate(iso: IsoDate, lang: Lang) {
  const [y, m, d] = iso.split('-').map(Number);
  return capitalize(
    new Date(y, m - 1, d).toLocaleDateString(lang === 'fr' ? 'fr-FR' : 'en-US', {
      weekday: 'long',
      day: 'numeric',
      month: 'long',
    }),
  );
}

/** "6 nov. · 14h00" from a full ISO timestamp. */
export function shortDateTime(at: string, lang: Lang) {
  const d = new Date(at);
  const day = d.toLocaleDateString(lang === 'fr' ? 'fr-FR' : 'en-US', { day: 'numeric', month: 'short' });
  const hhmm = `${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}`;
  return `${day} · ${formatTime(hhmm, lang)}`;
}

/** When the request happens ("Jeudi 6 novembre · 14h00"), or when it was sent for repairs. */
export function requestWhen(req: AnyRequest, lang: Lang, t: Strings) {
  switch (req.kind) {
    case 'maintenance':
      return t.requests.createdOn(shortDateTime(req.createdAt, lang));
    case 'gourmet':
      return `${longDate(req.date, lang)} · ${t.requests.timeRange(
        formatTime(req.startTime, lang),
        formatTime(req.endTime, lang),
      )}`;
    default:
      return `${longDate(req.date, lang)} · ${formatTime(req.time, lang)}`;
  }
}

/** Rent month an extra consumed on `date` is billed with (rule in selectors.charges). */
export function billingMonthLabel(date: IsoDate, lang: Lang) {
  return monthLabel(addMonths(monthOf(date), 1), lang);
}

/** "08:00", "09:00"… from `from` up to and including `to`. */
export function hourSlots(from: HourMinute, to: HourMinute): HourMinute[] {
  const start = Number(from.split(':')[0]);
  const end = Number(to.split(':')[0]);
  const out: HourMinute[] = [];
  for (let h = start; h <= end; h += 1) out.push(`${String(h).padStart(2, '0')}:00`);
  return out;
}

export const hourOf = (hhmm: HourMinute) => Number(hhmm.split(':')[0]);

/** Next `count` days starting `startOffset` days from today. */
export function nextDays(count: number, startOffset = 0, today = new Date()): IsoDate[] {
  return Array.from({ length: count }, (_, i) => isoDate(addDays(today, startOffset + i)));
}

/** Days (within `days`) and their hour slots that respect a minimum notice. */
export function slotsWithLeadTime(
  leadTimeHours: number,
  slots: HourMinute[],
  days = 21,
  now = new Date(),
): { date: IsoDate; times: HourMinute[] }[] {
  const earliest = now.getTime() + leadTimeHours * 3_600_000;
  return nextDays(days + Math.ceil(leadTimeHours / 24), 0, now)
    .map((date) => ({ date, times: slots.filter((s) => atTime(date, s).getTime() >= earliest) }))
    .filter((d) => d.times.length > 0)
    .slice(0, days);
}

/* ---------- Status pill ---------- */

export function StatusPill({ status }: { status: RequestStatus }) {
  const theme = useTheme();
  const { t } = useI18n();
  const color =
    status === 'done'
      ? theme.success
      : status === 'in_progress'
        ? theme.warning
        : status === 'scheduled'
          ? theme.text
          : theme.textSecondary;
  const background = status === 'done' ? theme.successSoft : theme.fill;
  return (
    <View style={[styles.pill, { backgroundColor: background }]}>
      <AppText variant="caption" color={color} style={{ fontFamily: Fonts.bodyMedium }}>
        {t.requests.status[status]}
      </AppText>
    </View>
  );
}

