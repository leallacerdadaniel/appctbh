/* ---------- Routes ---------- */

/** Routes of this feature as `Href` (the typed-routes file is regenerated by Metro, so cast until then). */
export const requestHref = (path: string) => path as Href;

/**
 * After a request is sent: the stack becomes … → Mes demandes → the new request, so Back lands on
 * the list, never on the form or the catalog again. Every request screen on top of the stack
 * (list, catalog, form) is dismissed, then the list and the request are pushed.
 */
export function useOpenSentRequest() {
  const navigation = useNavigation();
  return (id: string) => {
    const routes = navigation.getState()?.routes ?? [];
    let flow = 0;
    while (flow < routes.length - 1 && routes[routes.length - 1 - flow].name.startsWith('requests/')) flow++;
    if (flow > 0) router.dismiss(flow);
    router.push(requestHref('/requests'));
    router.push(requestHref(`/requests/${id}`));
  };
}

/* ---------- Belo Horizonte dates (UTC−3 all year, no daylight saving) ---------- */

const BH_OFFSET_MS = 3 * 3_600_000;
const pad = (n: number) => String(n).padStart(2, '0');
const capitalize = (s: string) => s.charAt(0).toUpperCase() + s.slice(1);
const locale = (lang: Lang) => (lang === 'fr' ? 'fr-FR' : 'en-US');

/** Today in Belo Horizonte, YYYY-MM-DD. */
export const bhToday = (now = Date.now()) => new Date(now - BH_OFFSET_MS).toISOString().slice(0, 10);

/** YYYY-MM-DD plus `n` days. */
export function addDays(iso: string, n: number) {
  const [y, m, d] = iso.split('-').map(Number);
  return new Date(Date.UTC(y, m - 1, d + n)).toISOString().slice(0, 10);
}

/** The instant of a Belo Horizonte date and time (same rule as the server). */
export const bhInstant = (date: string, time: string) => Date.parse(`${date}T${time}:00-03:00`);

export const toMinutes = (hhmm: string) => Number(hhmm.slice(0, 2)) * 60 + Number(hhmm.slice(3, 5));
export const fromMinutes = (minutes: number) => `${pad(Math.floor(minutes / 60))}:${pad(minutes % 60)}`;

/** "08:00", "09:00"… every hour from `from` up to and including `to`. */
export function hourSlots(from: string, to: string) {
  const out: string[] = [];
  for (let m = toMinutes(from); m <= toMinutes(to); m += 60) out.push(fromMinutes(m));
  return out;
}

/** The next `count` days that still have a slot after the minimum notice, with those slots. */
export function bookableDays(slots: string[], leadTimeHours: number, count = 21, now = Date.now()) {
  const earliest = now + leadTimeHours * 3_600_000;
  const today = bhToday(now);
  const out: { date: string; times: string[] }[] = [];
  for (let i = 0; out.length < count && i <= count + Math.ceil(leadTimeHours / 24); i++) {
    const date = addDays(today, i);
    const times = slots.filter((s) => bhInstant(date, s) >= earliest);
    if (times.length) out.push({ date, times });
  }
  return out;
}

/** "Lun. 10 nov." · "Mon, Nov 10" */
export const dayLabel = (iso: string, lang: Lang) => capitalize(formatDayDate(iso, lang, true));

/** "Lundi 10 novembre" · "Monday, November 10", with the year when it isn't this one. */
export function longDayLabel(iso: string, lang: Lang) {
  const [y, m, d] = iso.split('-').map(Number);
  return capitalize(
    new Date(y, m - 1, d).toLocaleDateString(locale(lang), {
      weekday: 'long',
      day: 'numeric',
      month: 'long',
      year: y !== new Date().getFullYear() ? 'numeric' : undefined,
    }),
  );
}

/** A timestamp of the database, in Belo Horizonte: "6 nov. · 14h00" · "Nov 6 · 2:00 PM". */
export function stampLabel(at: string, lang: Lang) {
  const local = new Date(Date.parse(at) - BH_OFFSET_MS).toISOString();
  const [y, m, d] = local.slice(0, 10).split('-').map(Number);
  const day = new Date(y, m - 1, d).toLocaleDateString(locale(lang), { day: 'numeric', month: 'short' });
  return `${day} · ${formatTime(local.slice(11, 16), lang)}`;
}

/** Rent month (YYYY-MM-01) by name: "décembre" · "December", with the year when it isn't this one. */
export function rentMonthLabel(month: string, lang: Lang) {
  const [y, m] = month.split('-').map(Number);
  return new Date(y, m - 1, 1).toLocaleDateString(locale(lang), {
    month: 'long',
    year: y !== new Date().getFullYear() ? 'numeric' : undefined,
  });
}

/* ---------- What a request is ---------- */

/** One line: "Laverie", "Réparation · Plomberie", "Départ tardif". */
export function requestTitle(req: TeamRequest, t: Strings, lang: Lang) {
  const r = t.requests;
  switch (req.kind) {
    case 'service':
      return localized(req.serviceName, lang) || r.kinds.service;
    case 'maintenance':
      return req.category ? `${r.kinds.maintenance} · ${r.maintenanceCategories[req.category]}` : r.kinds.maintenance;
    default:
      return r.kinds[req.kind];
  }
}

/** When it happens ("Lun. 10 nov. · 10h00"), or when it was sent for repairs. */
export function requestWhen(req: TeamRequest, t: Strings, lang: Lang) {
  if (req.kind === 'maintenance' || !req.date) return t.requests.sentOn(stampLabel(req.createdAt, lang));
  const day = dayLabel(req.date, lang);
  if (req.startTime && req.endTime) {
    return `${day} · ${t.requests.timeRange(formatTime(req.startTime, lang), formatTime(req.endTime, lang))}`;
  }
  return req.startTime ? `${day} · ${formatTime(req.startTime, lang)}` : day;
}

const CATEGORY_ICON: Record<ServiceCategory, IconName> = {
  cleaning: 'cleaning',
  laundry: 'laundry',
  chef: 'restaurant',
  transfer: 'car',
  other: 'receipt',
};

export const serviceCategoryIcon = (category: ServiceCategory) => CATEGORY_ICON[category] ?? 'receipt';

/** Row icon. Services take their catalog category's icon when the catalog still lists them. */
export function requestIcon(req: TeamRequest, catalog: CatalogItem[] = []): IconName {
  switch (req.kind) {
    case 'service': {
      const svc = catalog.find((c) => c.id === req.serviceId);
      return svc ? serviceCategoryIcon(svc.category) : 'receipt';
    }
    case 'maintenance':
      return 'wrench';
    case 'late_checkout':
      return 'luggage';
    case 'early_checkin':
      return 'key';
    case 'gourmet':
      return 'grill';
  }
}

/** Error code of a failed call → the sentence to show. */
export function requestErrorText(error: unknown, t: Strings) {
  const e = t.requests.errors;
  const code = error instanceof AppApiError ? error.code : 'server';
  if (code === 'tooSoon') return e.tooSoon;
  if (code === 'taken') return e.taken;
  if (code === 'invalid') return e.invalid;
  if (code === 'forbidden') return e.cancelForbidden;
  return e.server;
}

/* ---------- Loading gate ---------- */

/** Renders its children once the requests are loaded; a retry card if the first load failed. */
export function RequestsGate({ children }: { children: (data: RequestsData) => ReactNode }) {
  const { t } = useI18n();
  const { state, reload } = useRequests();
  if (state.status === 'ready') return <>{children(state.data)}</>;
  if (state.status === 'loading') return <LoadingState label={t.common.loading} />;
  return <RetryCard message={t.requests.unavailable} retryLabel={t.requests.retry} onRetry={reload} />;
}

/* ---------- Status pill (never brand red) ---------- */

export function StatusPill({ status }: { status: RequestStatus }) {
  const theme = useTheme();
  const { t } = useI18n();
  const color =
    status === 'done'
      ? theme.success
      : status === 'in_progress'
        ? theme.warning
        : status === 'scheduled'
          ? theme.text
          : theme.textSecondary;
  return (
    <View style={[styles.pill, { backgroundColor: status === 'done' ? theme.successSoft : theme.fill }]}>
      <AppText variant="caption" color={color} style={{ fontFamily: Fonts.bodyMedium }}>
        {t.requests.status[status]}
      </AppText>
    </View>
  );
}

