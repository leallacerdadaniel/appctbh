/** Days as chips: "Aujourd’hui", "Demain", then "Lun. 10 nov.". */
export function DateChips({
  dates,
  value,
  onChange,
}: {
  dates: string[];
  value?: string;
  onChange: (date: string) => void;
}) {
  const { t, lang } = useI18n();
  const today = bhToday();
  const tomorrow = addDays(today, 1);
  const label = (d: string) => (d === today ? t.requests.today : d === tomorrow ? t.requests.tomorrow : dayLabel(d, lang));
  return (
    <ChipScroller>
      {dates.map((d) => (
        <Chip key={d} label={label(d)} selected={d === value} onPress={() => onChange(d)} />
      ))}
    </ChipScroller>
  );
}

/** Hours as wrapping chips ("10h00" · "10:00 AM"). */
export function TimeChips({
  times,
  value,
  onChange,
}: {
  times: string[];
  value?: string;
  onChange: (time: string) => void;
}) {
  const { lang } = useI18n();
  return (
    <ChipWrap>
      {times.map((time) => (
        <Chip key={time} label={formatTime(time, lang)} selected={time === value} onPress={() => onChange(time)} />
      ))}
    </ChipWrap>
  );
}

/** − value + with 44 pt round buttons. */
export function Stepper({
  value,
  min = 1,
  max,
  onChange,
  format,
}: {
  value: number;
  min?: number;
  max: number;
  onChange: (n: number) => void;
  format?: (n: number) => string;
}) {
  const theme = useTheme();
  const { t } = useI18n();
  const button = (icon: IconName, label: string, next: number, disabled: boolean) => (
    <Pressable
      accessibilityRole="button"
      accessibilityLabel={label}
      accessibilityState={{ disabled }}
      disabled={disabled}
      onPress={() => {
        tapFeedback();
        onChange(next);
      }}
      style={({ pressed }) => [
        styles.stepButton,
        { backgroundColor: theme.fill, opacity: disabled ? 0.4 : pressed ? 0.6 : 1 },
      ]}>
      <Icon name={icon} size={18} color={theme.text} />
    </Pressable>
  );
  return (
    <View style={styles.stepper}>
      {button('minus', t.requests.decrease, value - 1, value <= min)}
      <AppText accessibilityLiveRegion="polite" style={styles.stepValue}>
        {format ? format(value) : String(value)}
      </AppText>
      {button('plus', t.requests.increase, value + 1, value >= max)}
    </View>
  );
}

/** 1–5 stars (44 pt each), the yellow rating star when chosen. Read-only without `onChange`. */
export function StarRating({
  value,
  onChange,
  size = 32,
}: {
  value: number;
  onChange?: (n: number) => void;
  size?: number;
}) {
  const theme = useTheme();
  const { t } = useI18n();
  return (
    <View
      style={[styles.stars, onChange && { marginLeft: -6 }]}
      accessibilityRole={onChange ? 'radiogroup' : undefined}
      accessibilityLabel={onChange ? undefined : t.requests.rateStar(value)}>
      {[1, 2, 3, 4, 5].map((n) => {
        const star = <Icon name="star" size={size} color={n <= value ? theme.star : theme.line} />;
        if (!onChange) return <View key={n}>{star}</View>;
        return (
          <Pressable
            key={n}
            accessibilityRole="radio"
            accessibilityLabel={t.requests.rateStar(n)}
            accessibilityState={{ checked: n === value }}
            onPress={() => {
              tapFeedback();
              onChange(n);
            }}
            style={styles.starButton}>
            {star}
          </Pressable>
        );
      })}
    </View>
  );
}

/** Icon + text on a soft background, for tips and warnings (never brand red). */
export function Notice({ icon, text, tone = 'info' }: { icon: IconName; text: string; tone?: 'info' | 'warning' }) {
  const theme = useTheme();
  const color = tone === 'warning' ? theme.warning : theme.textSecondary;
  return (
    <View style={[styles.notice, { backgroundColor: theme.fill }]}>
      <Icon name={icon} size={18} color={color} />
      <AppText variant="callout" color={tone === 'warning' ? theme.warning : theme.text} style={{ flex: 1 }}>
        {text}
      </AppText>
    </View>
  );
}

/* ---------- Timeline ---------- */

/** Each change of status, newest first: what, when, who ("Chez Toi" or "Vous") and the team's note. */
export function Timeline({ events }: { events: RequestEvent[] }) {
  const theme = useTheme();
  const { t, lang } = useI18n();
  const r = t.requests;
  const list = [...events].sort((a, b) => b.at.localeCompare(a.at));
  return (
    <View>
      {list.map((e, i) => {
        const latest = i === 0;
        const dot =
          e.status === 'done'
            ? theme.success
            : e.status === 'in_progress'
              ? theme.warning
              : latest
                ? theme.text
                : theme.textTertiary;
        const label = e.status === 'received' && !e.byTeam ? r.sentStep : r.status[e.status];
        return (
          <View key={`${e.at}-${i}`} style={styles.event}>
            <View style={styles.rail}>
              <View style={[styles.dot, { backgroundColor: dot }]} />
              {i < list.length - 1 && <View style={[styles.line, { backgroundColor: theme.line }]} />}
            </View>
            <View style={[styles.eventText, i === list.length - 1 && { paddingBottom: 0 }]}>
              <AppText style={latest ? { fontFamily: Fonts.bodyMedium } : undefined}>{label}</AppText>
              <AppText variant="caption" color={theme.textSecondary}>
                {stampLabel(e.at, lang)} · {e.byTeam ? r.byTeam : r.byYou}
              </AppText>
              {e.note ? <AppText variant="callout">{e.note}</AppText> : null}
            </View>
          </View>
        );
      })}
    </View>
  );
}

